package org.openoffline.translator.android

import org.junit.Assert.assertEquals
import org.junit.Test

class RussianSpokenNumbersTest {
    private fun n(text: String) = RussianSpokenNumbers.normalize(text)
    @Test fun datesYearsAndClockTimesBecomeDigits() {
        assertEquals("Встречаемся 23 марта в половине восьмого вечера у входа в метро.", n("Встречаемся двадцать третьего марта в половине восьмого вечера у входа в метро."))
        assertEquals("Поезд отправляется 14 февраля в 7:45 утра с ленинградского вокзала.", n("Поезд отправляется четырнадцатого февраля в семь сорок пять утра с ленинградского вокзала."))
        assertEquals("Мой рейс задержали до 22:30 прилетаю 1 января 2027 года.", n("Мой рейс задержали до двадцати двух тридцати прилетаю первого января две тысячи двадцать седьмого года."))
        assertEquals("Запись к врачу на пятницу 9 мая в 11:15.", n("Запись к врачу на пятницу девятое мая в одиннадцать пятнадцать."))
        assertEquals("Совещание перенесли с понедельника на среду 3 июня с 15:00 до 16:30.", n("Совещание перенесли с понедельника на среду третье июня с пятнадцати ноль ноль до шестнадцати тридцати."))
        assertEquals("Скидки действуют с 1-го по 10 ноября магазин работает с 9 до 21 часа.", n("Скидки действуют с первого по десятое ноября магазин работает с девяти до двадцати одного часа."))
        assertEquals("Заселение 18 декабря после 14 часов выезд 21-го до полудня.", n("Заселение восемнадцатого декабря после четырнадцати часов выезд двадцать первого до полудня."))
    }
    @Test fun ambiguousAndOrdinaryNumbersStaySpoken() {
        val unchanged = listOf(
            "Напомни мне в среду без четверти девять позвонить маме а в четверг в шесть утра поехать в аэропорт.",
            "Ведь они могут понижать броню на четыре единицы.",
            "Тинкер третьим героем опять же.",
            "Герой получил две единицы силы это плюс пятьдесят здоровья.",
            "Это в два раза быстрее и в одном из патчей.")
        unchanged.forEach { assertEquals(it, n(it)) }
    }
}
