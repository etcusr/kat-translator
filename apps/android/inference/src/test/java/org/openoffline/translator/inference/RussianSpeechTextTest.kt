package org.openoffline.translator.inference

import org.junit.Assert.assertEquals
import org.junit.Test

/** Same cases as OfflineCore RussianSpeechTextTests on Apple. */
class RussianSpeechTextTest {
    @Test fun expandsKnownForms() {
        val cases = listOf(
            "Измените дату приезда с 15-го на 16-е октября." to "Измените дату приезда с пятнадцатого на шестнадцатое октября.",
            "Я имел в виду 17-е, а не 16-е." to "Я имел в виду семнадцатое, а не шестнадцатое.",
            "в 2026-м году" to "в две тысячи двадцать шестом году",
            "3-я линия, 2-й этаж, 40-го размера" to "третья линия, второй этаж, сорокового размера",
            "к 21-му числу" to "к двадцать первому числу",
            "в 1990-х" to "в тысяча девятьсот девяностых",
            "100-й раз" to "сотый раз",
            "на 1-й улице" to "на первой улице",
            "до 3-й остановки" to "до третьей остановки",
            "к 2-ой станции" to "к второй станции",
            "перед 3-й школой" to "перед третьей школой",
            "80-е годы" to "восьмидесятые годы",
            "3-е места" to "третьи места",
            "2-е место" to "второе место",
            "3-и места" to "третьи места",
            "80-ые годы" to "восьмидесятые годы",
            "перед 1-м рейсом" to "перед первым рейсом",
            "над 3-м этажом" to "над третьим этажом",
            "с 2-м ребёнком" to "с вторым ребёнком",
            "в 1-м классе" to "в первом классе",
            "о 3-м месте" to "о третьем месте",
            "Перед 21-м рейсом" to "Перед двадцать первым рейсом",
            "Перенесите с 15-го на 16-е октября." to "Перенесите с пятнадцатого на шестнадцатое октября.",
            "31-е декабря" to "тридцать первое декабря",
            "3-е число" to "третье число",
            "3-им рейсом, 1-ом классе" to "третьим рейсом, первом классе",
            "1-ая улица, 3-ю станцию" to "первая улица, третью станцию",
            "2-ые места, 3-ие места" to "вторые места, третьи места"
        )
        for ((input, expected) in cases) assertEquals(input, expected, RussianSpeechText.expandOrdinals(input))
    }
    @Test fun leavesOtherTextUntouched() {
        val cases = listOf("Цена 120 евро.", "Звоните 8-800-555-35-35", "Рейс SU-1234", "2,5-й", "16 октября", "2000-й год", "1-й", "с 1-й", "1-м", "80-е", "1-й авеню", "1-й новой улице", "3-е неизвестные", "1-м способом", "1-й. улице", "на 1-м и 2-м", "3-е пришли")
        for (input in cases) assertEquals(input, input, RussianSpeechText.expandOrdinals(input))
    }
}
