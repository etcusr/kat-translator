#!/usr/bin/env python3
"""Generate Android language data from the existing shared Apple catalog, without a forked list."""
import argparse,json,re
from pathlib import Path
root=Path(__file__).resolve().parents[2]
source=(root/'shared/packages/OfflineCore/Sources/OfflineCore/LanguageSelection.swift').read_text()
flags=(root/'shared/apple/Conversation/LanguageFlag.swift').read_text()
regions={language:region for region,ids in re.findall(r'"([A-Z]{2})": \[([^]]+)\]',flags) for language in re.findall(r'"([^"]+)"',ids)}
rows=re.findall(r'\.init\(id: "([^"]+)", name: "([^"]+)", englishName: "([^"]+)", indexName: "([^"]+)"',source)
assert len(rows)>100 and len({row[0] for row in rows})==len(rows)
def quote(s):return json.dumps(s,ensure_ascii=False).replace('$','\\$')
body='// Generated by scripts/android/generate-ui-catalog.py. Do not edit.\npackage org.openoffline.translator.inference\n\ndata class IndexLanguage(val id:String,val russian:String,val english:String,val promptName:String,val flag:String)\nobject IndexLanguages {\n    val all=listOf(\n'
for id,ru,en,prompt in rows:
 flag=''.join(chr(127397+ord(c)) for c in regions[id]) if id in regions else '🌐'
 body+='        IndexLanguage('+','.join(map(quote,[id,ru,en,prompt,flag]))+'),\n'
body+='    )\n    val byId=all.associateBy { it.id }\n}\n'
path=root/'apps/android/inference/src/main/java/org/openoffline/translator/inference/IndexLanguages.kt'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
if args.check:
 assert path.read_text()==body,'Android language catalog drift; run scripts/android/generate-ui-catalog.py'
else:path.write_text(body)
print(f'Android: {len(rows)} Index languages match shared iOS catalog')
