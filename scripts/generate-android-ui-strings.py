#!/usr/bin/env python3
"""Generate Android UI dictionaries from the shared catalog and Android-specific strings."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'apps/android/app/src/main/java/org/openoffline/translator/android'
def render():
    catalog=json.loads((ROOT/'assets/bundled/Localizable.xcstrings').read_text())['strings']
    extra=json.loads((ROOT/'assets/localization/android-ui.json').read_text())
    result={}
    for language in ['en','es','tr']:
        values={key.replace('%%','%'):entry['localizations'][language]['stringUnit']['value'].replace('%%','%') for key,entry in catalog.items() if 'stringUnit' in entry['localizations'][language]}
        values.update({key:entry[language] for key,entry in extra.items()})
        def q(value):return json.dumps(value,ensure_ascii=False).replace('$','\\$')
        rows=sorted(values.items());chunks=[rows[i:i+100] for i in range(0,len(rows),100)]
        name='UiStrings'+language.title()
        text='package org.openoffline.translator.android\n\n// Generated by scripts/generate-android-ui-strings.py; edit the source catalogs.\ninternal object '+name+' {\n    val values: Map<String, String> by lazy { buildMap {\n'
        text+=''.join(f'        putAll(part{i}())\n' for i in range(len(chunks)))+'    } }\n'
        for i,chunk in enumerate(chunks):
            text+=f'    private fun part{i}() = mapOf(\n'+''.join(f'        {q(k)} to {q(v)},\n' for k,v in chunk)+'    )\n'
        result[OUT/(name+'.kt')]=text+'}\n'
    return result
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,text in render().items():
        if args.check:
            assert path.exists() and path.read_text()==text,f'Outdated generated strings: {path.relative_to(ROOT)}'
        else:path.write_text(text)
    print('Android UI dictionaries: EN/ES/TR synchronized')
