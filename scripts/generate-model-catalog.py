#!/usr/bin/env python3
"""Generate the Apple descriptor adapter from the universal model catalog."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def generate():
    data=json.loads((ROOT/'assets/catalogs/models.json').read_text())
    if data['schemaVersion']!=1: raise ValueError('Unsupported model catalog schema')
    quote=lambda s:json.dumps(s,ensure_ascii=False)
    out='// Generated by scripts/generate-model-catalog.py; edit assets/catalogs/models.json.\nimport Foundation\n\npublic enum SharedModelAssets {\n'
    for m in data['models']:
        title=quote(m['title'])
        if m['localized']:title='L10n.text('+title+')'
        out+=f"    public static let {m['symbol']} = ModelDescriptor(id: {quote(m['id'])}, title: {title},\n        remoteURL: URL(string: {quote(m['remoteURL'])})!,\n        byteCount: {m['byteCount']}, sha256: {quote(m['sha256'])})\n"
    return out+'}\n'
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    destination=ROOT/'shared/packages/OfflineCore/Sources/OfflineCore/SharedModelAssets.swift';content=generate()
    if args.check:
        if not destination.exists() or destination.read_text()!=content:raise SystemExit('Model adapter stale: run scripts/generate-model-catalog.py')
    else:destination.write_text(content)
